// ============================================================================
// P7 — build the digital/social presence data module.
//
// Official websites come from the published institution records (which carry
// website + websiteStatus). Social accounts come from data/durable/store.db
// (social_accounts table, currently 0 rows). Empty -> empty arrays + an honest
// provenance note. Nothing is fabricated.
//
// Usage: npm run build:social
// ============================================================================
// eslint-disable-next-line @typescript-eslint/no-require-imports
const Database = require("better-sqlite3") as new (p: string, o?: { readonly?: boolean }) => {
  prepare: (sql: string) => { all: (...args: unknown[]) => unknown[] };
  close: () => void;
};
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { institutions } from "../src/data/institutions";

const ROOT = resolve(__dirname, "..");

interface SocialRow {
  id: string;
  institution_id: string;
  platform: string;
  handle: string | null;
  url: string;
  verified: number;
  is_active: number;
  last_checked: string | null;
  source_id: string | null;
}

function main(): void {
  const db = new Database(resolve(ROOT, "data/durable/store.db"), { readonly: true });
  const socialRows = db.prepare(
    "SELECT id, institution_id, platform, handle, url, verified, is_active, last_checked, source_id FROM social_accounts",
  ).all() as SocialRow[];
  db.close();

  const slugById = new Map(institutions.map((i) => [i.id, i.slug]));

  const officialWebsites = institutions
    .filter((i) => i.officialWebsite)
    .map((i) => ({
      institutionId: i.id,
      institutionSlug: i.slug,
      institutionName: i.name,
      url: i.officialWebsite as string,
      status: i.websiteStatus,
    }));

  const socialAccounts = socialRows.map((r) => ({
    id: r.id,
    institutionId: r.institution_id,
    institutionSlug: slugById.get(r.institution_id) ?? null,
    platform: r.platform,
    handle: r.handle,
    url: r.url,
    status: r.verified === 1 ? "verified" : "candidate",
    sourceId: r.source_id,
  }));

  const verifiedCount = officialWebsites.filter((w) => w.status === "verified").length;

  const provenance =
    socialAccounts.length === 0
      ? `Official websites: ${officialWebsites.length} recorded (${verifiedCount} verified, ${officialWebsites.length - verifiedCount} candidate). Social accounts: 0 recorded — the durable store holds 0 social_accounts rows, so none are shown. Logos and brand colours are never guessed (see BRANDING_NOTE).`
      : `Official websites: ${officialWebsites.length} (${verifiedCount} verified). Social accounts: ${socialAccounts.length}.`;

  const body = `// ============================================================================
// P7 — digital / social presence data (generated by scripts/build-social-module.ts).
//
// Do not edit by hand. Re-run: npm run build:social
//
// Official websites come from the published institution records (with their
// verified/candidate status). Social accounts come from data/durable/store.db
// (social_accounts), which holds 0 rows today, so that list is honestly empty.
// ============================================================================
export interface OfficialWebsite {
  institutionId: string;
  institutionSlug: string;
  institutionName: string;
  url: string;
  status: string;
}

export interface SocialAccount {
  id: string;
  institutionId: string | null;
  institutionSlug: string | null;
  platform: string;
  handle: string | null;
  url: string | null;
  status: string;
  sourceId: string | null;
}

export const officialWebsites: OfficialWebsite[] = ${JSON.stringify(officialWebsites, null, 2)};

export const socialAccounts: SocialAccount[] = ${JSON.stringify(socialAccounts, null, 2)};

export const digitalProvenance = ${JSON.stringify(provenance)};
`;

  const outPath = resolve(ROOT, "src/data/social.ts");
  writeFileSync(outPath, body, "utf8");
  console.log(`[build-social] officialWebsites=${officialWebsites.length} (${verifiedCount} verified) socialAccounts=${socialAccounts.length}`);
  console.log(`[build-social] wrote ${outPath}`);
}

main();
