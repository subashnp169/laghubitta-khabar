// ============================================================================
// P4-1 — build snapshot-diff alerts from two dated evidence databases.
//
// Reads `data_assertions` from a "before" and an "after" evidence DB, diffs
// them with the pure engine in `lib/diff.ts`, and writes the result to
// `src/data/diff-alerts.ts` so the alerts page can surface "what changed since
// the last run" with REAL observation timestamps (never invented).
//
// Usage:
//   npm run build:diff-alerts                              (default pair)
//   npm run build:diff-alerts -- --before <db> --after <db>
//
// The generated module is committed (like `src/data/former-names.ts`); re-run
// this script when a new dated evidence DB lands. It fails loudly if either DB
// is missing or holds no assertions, so an empty/fabricated module can never be
// shipped silently. An empty DIFF (no changes) is legitimate and produces [].
// ============================================================================
// eslint-disable-next-line @typescript-eslint/no-require-imports
const Database = require("better-sqlite3") as new (p: string, o?: { readonly?: boolean }) => {
  prepare: (sql: string) => { all: (...args: unknown[]) => unknown[] };
  close: () => void;
};
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { diffAssertions, type DiffAssertion, type DiffChange } from "../lib/diff";

const ROOT = resolve(__dirname, "..");

interface DbRow {
  id: string;
  entity_type: string;
  entity_id: string;
  field_name: string;
  value: string;
  source_id: string;
  observed_at: string;
  confidence: number | null;
  verification_status: string;
}

function readAssertions(dbPath: string): DiffAssertion[] {
  const db = new Database(dbPath, { readonly: true });
  try {
    const rows = db.prepare(
      "SELECT id, entity_type, entity_id, field_name, value, source_id, observed_at, confidence, verification_status FROM data_assertions",
    ).all() as DbRow[];
    return rows
      .filter((r) => typeof r.observed_at === "string" && r.observed_at.trim().length > 0)
      .map((r) => ({
        id: r.id,
        entityType: r.entity_type,
        entityId: r.entity_id,
        fieldName: r.field_name,
        value: r.value,
        sourceId: r.source_id,
        observedAt: r.observed_at,
        confidence: r.confidence,
        verificationStatus: r.verification_status,
      }));
  } finally {
    db.close();
  }
}

function parseArgs(argv: string[]): { before: string; after: string } {
  const defaults = {
    before: "data/pilot/evidence/pilot-people-2026-09-27-ext-c-pass1.db",
    after: "data/pilot/evidence/pilot-people-ext-c-pass2.db",
  };
  let before = defaults.before;
  let after = defaults.after;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--before" && argv[i + 1]) { before = argv[i + 1]; i += 1; }
    else if (argv[i] === "--after" && argv[i + 1]) { after = argv[i + 1]; i += 1; }
  }
  return { before: resolve(ROOT, before), after: resolve(ROOT, after) };
}

function main(): void {
  const { before, after } = parseArgs(process.argv.slice(2));

  console.log(`[build-diff-alerts] before: ${before}`);
  console.log(`[build-diff-alerts] after:  ${after}`);

  const beforeRows = readAssertions(before);
  const afterRows = readAssertions(after);

  if (beforeRows.length === 0) throw new Error(`before DB has no timestamped assertions: ${before}`);
  if (afterRows.length === 0) throw new Error(`after DB has no timestamped assertions: ${after}`);

  const changes: DiffChange[] = diffAssertions(beforeRows, afterRows);

  const beforeLabel = before.split(/[\\/]/).pop() ?? before;
  const afterLabel = after.split(/[\\/]/).pop() ?? after;

  const body = `// ============================================================================
// P4-1 — snapshot-diff changes ("what changed since the last run").
//
// GENERATED by scripts/build-diff-alerts.ts — do not edit by hand. Re-run:
//   npm run build:diff-alerts
//
// Source: diff of data_assertions between two dated evidence databases.
//   before: ${beforeLabel}
//   after:  ${afterLabel}
// Every entry carries the REAL observation timestamp of the row that moved;
// none is invented. An empty array means the two runs agree.
// ============================================================================
import type { DiffChange } from "../../lib/diff";

export const diffAlertsSource = {
  before: ${JSON.stringify(beforeLabel)},
  after: ${JSON.stringify(afterLabel)},
  beforeCount: ${beforeRows.length},
  afterCount: ${afterRows.length},
  generatedAt: ${JSON.stringify(new Date().toISOString())},
};

export const diffChanges: DiffChange[] = ${JSON.stringify(changes, null, 2)};
`;

  const outPath = resolve(ROOT, "src/data/diff-alerts.ts");
  writeFileSync(outPath, body, "utf8");

  const added = changes.filter((c) => c.kind === "added").length;
  const removed = changes.filter((c) => c.kind === "removed").length;
  console.log(`[build-diff-alerts] before=${beforeRows.length} after=${afterRows.length} added=${added} removed=${removed} total=${changes.length}`);
  console.log(`[build-diff-alerts] wrote ${outPath}`);
}

main();