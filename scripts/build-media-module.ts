// ============================================================================
// P10 — build the media/activity data module from the durable store.
//
// Reads `videos`, `posts`, `digital_services` from data/durable/store.db and
// projects the published/recorded rows into src/data/media.ts so the /media
// page can render them. Empty tables produce empty arrays + an honest
// provenance note — never fabricated rows.
//
// Usage: npm run build:media
// ============================================================================
// eslint-disable-next-line @typescript-eslint/no-require-imports
const Database = require("better-sqlite3") as new (p: string, o?: { readonly?: boolean }) => {
  prepare: (sql: string) => { all: (...args: unknown[]) => unknown[] };
  close: () => void;
};
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(__dirname, "..");

interface InstRow { id: string; slug: string }

function main(): void {
  const dbPath = resolve(ROOT, "data/durable/store.db");
  const db = new Database(dbPath, { readonly: true });

  const instRows = db.prepare("SELECT id, slug FROM institutions").all() as InstRow[];
  const slugById = new Map(instRows.map((r) => [r.id, r.slug]));

  const videoRows = db.prepare(
    "SELECT id, slug, institution_id, title, video_type, embed_url, thumbnail_url, published_at, status, source_id FROM videos WHERE status IN ('PUBLISHED','ARCHIVED')",
  ).all() as Array<Record<string, unknown>>;

  const postRows = db.prepare(
    "SELECT id, slug, institution_id, source_type, post_kind, category, title, excerpt, url, published_at, status, source_id FROM posts WHERE status IN ('PUBLISHED','SCHEDULED')",
  ).all() as Array<Record<string, unknown>>;

  const serviceRows = db.prepare(
    "SELECT id, institution_id, service_type, name, url, description, status, source_id, last_verified_at FROM digital_services",
  ).all() as Array<Record<string, unknown>>;

  db.close();

  const videos = videoRows.map((r) => ({
    id: String(r.id),
    slug: r.slug == null ? null : String(r.slug),
    institutionId: r.institution_id == null ? null : String(r.institution_id),
    institutionSlug: r.institution_id == null ? null : (slugById.get(String(r.institution_id)) ?? null),
    title: String(r.title),
    videoType: String(r.video_type),
    embedUrl: r.embed_url == null ? null : String(r.embed_url),
    thumbnailUrl: r.thumbnail_url == null ? null : String(r.thumbnail_url),
    publishedAt: r.published_at == null ? null : String(r.published_at),
    status: String(r.status),
    sourceId: r.source_id == null ? null : String(r.source_id),
  }));

  const posts = postRows.map((r) => ({
    id: String(r.id),
    slug: String(r.slug),
    institutionId: r.institution_id == null ? null : String(r.institution_id),
    institutionSlug: r.institution_id == null ? null : (slugById.get(String(r.institution_id)) ?? null),
    sourceType: String(r.source_type),
    postKind: String(r.post_kind),
    category: r.category == null ? null : String(r.category),
    title: String(r.title),
    excerpt: r.excerpt == null ? null : String(r.excerpt),
    url: r.url == null ? null : String(r.url),
    publishedAt: String(r.published_at),
    status: String(r.status),
    sourceId: r.source_id == null ? null : String(r.source_id),
  }));

  const digitalServices = serviceRows.map((r) => ({
    id: String(r.id),
    institutionId: String(r.institution_id),
    institutionSlug: slugById.get(String(r.institution_id)) ?? null,
    serviceType: String(r.service_type),
    name: String(r.name),
    url: r.url == null ? null : String(r.url),
    description: r.description == null ? null : String(r.description),
    status: String(r.status),
    sourceId: r.source_id == null ? null : String(r.source_id),
    lastVerifiedAt: r.last_verified_at == null ? null : String(r.last_verified_at),
  }));

  const provenance =
    videos.length === 0 && posts.length === 0 && digitalServices.length === 0
      ? "No media, posts or digital services are recorded yet. The durable store holds 0 rows in videos, posts and digital_services, so this module is honestly empty. It will populate when media is ingested; the /media page states the absence rather than implying coverage."
      : `Projected from data/durable/store.db: ${videos.length} video(s), ${posts.length} post(s), ${digitalServices.length} digital service(s).`;

  const body = `// ============================================================================
// P10 — media / activity data (generated by scripts/build-media-module.ts).
//
// Do not edit by hand. Re-run: npm run build:media
//
// Empty today because the durable store holds no media/post/digital-service
// rows. The /media page renders the honest empty state; nothing is fabricated.
// ============================================================================
export interface MediaVideo {
  id: string;
  slug: string | null;
  institutionId: string | null;
  institutionSlug: string | null;
  title: string;
  videoType: string;
  embedUrl: string | null;
  thumbnailUrl: string | null;
  publishedAt: string | null;
  status: string;
  sourceId: string | null;
}

export interface MediaPost {
  id: string;
  slug: string;
  institutionId: string | null;
  institutionSlug: string | null;
  sourceType: string;
  postKind: string;
  category: string | null;
  title: string;
  excerpt: string | null;
  url: string | null;
  publishedAt: string;
  status: string;
  sourceId: string | null;
}

export interface MediaDigitalService {
  id: string;
  institutionId: string;
  institutionSlug: string | null;
  serviceType: string;
  name: string;
  url: string | null;
  description: string | null;
  status: string;
  sourceId: string | null;
  lastVerifiedAt: string | null;
}

export const videos: MediaVideo[] = ${JSON.stringify(videos, null, 2)};

export const posts: MediaPost[] = ${JSON.stringify(posts, null, 2)};

export const digitalServices: MediaDigitalService[] = ${JSON.stringify(digitalServices, null, 2)};

export const mediaProvenance = ${JSON.stringify(provenance)};
`;

  const outPath = resolve(ROOT, "src/data/media.ts");
  writeFileSync(outPath, body, "utf8");
  console.log(`[build-media] videos=${videos.length} posts=${posts.length} digitalServices=${digitalServices.length}`);
  console.log(`[build-media] wrote ${outPath}`);
}

main();
