// ============================================================================
// V1.1 — build stale-source alerts from ingestion runs + source-field-groups.
//
// Reads ingestion_runs and data/master/source-field-groups.json, computes
// days-since-last-successful-run per source, and flags (source, field-group)
// pairs past their field_refresh_policies threshold. Writes
// src/data/stale-sources.ts so /alerts can surface them with REAL timestamps.
//
// Usage: npm run build:stale-sources
// ============================================================================
// eslint-disable-next-line @typescript-eslint/no-require-imports
const Database = require("better-sqlite3") as new (p: string, o?: { readonly?: boolean }) => {
  prepare: (sql: string) => { all: (...args: unknown[]) => unknown[] };
  close: () => void;
};
import { writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(__dirname, "..");

interface RunRow { ingestion_source_id: string; status: string; started_at: string }

function main(): void {
  const db = new Database(resolve(ROOT, "data/durable/store.db"), { readonly: true });
  const runs = db.prepare("SELECT ingestion_source_id, status, started_at FROM ingestion_runs").all() as RunRow[];
  db.close();

  const mappingDoc = JSON.parse(readFileSync(resolve(ROOT, "data/master/source-field-groups.json"), "utf8")) as { mapping: Record<string, string[]> };

  // read policies from db instead
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const db2 = new (require("better-sqlite3"))(resolve(ROOT, "data/durable/store.db"), { readonly: true });
  const policyRows = db2.prepare("SELECT field_group, refresh_days FROM field_refresh_policies").all() as Array<{ field_group: string; refresh_days: number }>;
  db2.close();
  const refreshDays = new Map(policyRows.map((p) => [p.field_group, p.refresh_days]));

  // last successful run per source
  const lastBySource = new Map<string, string>();
  for (const r of runs) {
    if (r.status !== "SUCCESS") continue;
    const cur = lastBySource.get(r.ingestion_source_id);
    if (!cur || r.started_at > cur) lastBySource.set(r.ingestion_source_id, r.started_at);
  }

  const asOf = [...lastBySource.values()].sort().pop() ?? new Date().toISOString();
  const asOfMs = new Date(asOf).getTime();

  interface StaleSource { source: string; days: number; groups: string[]; lastRun: string }
  const stale: StaleSource[] = [];
  for (const [src, last] of lastBySource) {
    const days = Math.floor((asOfMs - new Date(last).getTime()) / (24 * 60 * 60 * 1000));
    const groups = mappingDoc.mapping[src] ?? [];
    const staleGroups = groups.filter((g) => {
      const thr = refreshDays.get(g);
      return thr !== undefined && days > thr;
    });
    if (staleGroups.length > 0) stale.push({ source: src, days, groups: staleGroups, lastRun: last });
  }
  stale.sort((a, b) => b.days - a.days || a.source.localeCompare(b.source));

  const body = `// ============================================================================
// V1.1 — stale source alerts (generated by scripts/build-stale-sources.ts).
//
// Do not edit by hand. Re-run: npm run build:stale-sources
//
// Each entry is a (source, field-group) pair past its field_refresh_policies
// threshold, with the REAL last-successful-run timestamp. Empty array means
// nothing is stale.
// ============================================================================
export interface StaleSource {
  source: string;
  days: number;
  groups: string[];
  lastRun: string;
}

export const staleSources: StaleSource[] = ${JSON.stringify(stale, null, 2)};

export const staleSourcesAsOf = ${JSON.stringify(asOf)};
`;

  const outPath = resolve(ROOT, "src/data/stale-sources.ts");
  writeFileSync(outPath, body, "utf8");
  console.log(`[build:stale-sources] stale pairs=${stale.length} sources=${lastBySource.size} asOf=${asOf}`);
  console.log(`[build:stale-sources] wrote ${outPath}`);
}

main();
