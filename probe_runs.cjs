const Database = require('better-sqlite3');
const db = new Database('data/durable/store.db', { readonly: true });
console.log("=== ingestion_runs columns ===");
console.log(db.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name='ingestion_runs'").get().sql);
console.log("=== distinct status ===");
console.log(db.prepare("SELECT status, COUNT(*) c FROM ingestion_runs GROUP BY status").all());
console.log("=== min/max started_at ===");
console.log(db.prepare("SELECT MIN(started_at) mn, MAX(started_at) mx FROM ingestion_runs").get());
console.log("=== runs by source (top 5 by count) ===");
console.log(db.prepare("SELECT ingestion_source_id, COUNT(*) c, SUM(CASE WHEN status='SUCCESS' THEN 1 ELSE 0 END) succ FROM ingestion_runs GROUP BY ingestion_source_id ORDER BY c DESC LIMIT 5").all());
console.log("=== field_refresh_policies ===");
console.log(db.prepare("SELECT * FROM field_refresh_policies").all());
console.log("=== data_conflicts columns ===");
console.log(db.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name='data_conflicts'").get().sql);
console.log("=== data_conflicts count ===");
console.log(db.prepare("SELECT COUNT(*) c FROM data_conflicts").get());
console.log("=== official_links count ===");
console.log(db.prepare("SELECT COUNT(*) c FROM official_links").get());
console.log("=== social_accounts count ===");
console.log(db.prepare("SELECT COUNT(*) c FROM social_accounts").get());
db.close();
